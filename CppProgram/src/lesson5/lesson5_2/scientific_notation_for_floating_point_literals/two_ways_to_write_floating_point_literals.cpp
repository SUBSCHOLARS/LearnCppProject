// write in decimal format
double pi {3.14159}; // 3.14159 is a double literal in standard notation
double d {-1.23}; // the literal can be negative
double why {0.}; // syntactically acceptable, but avoid this because it is hard to see the decimal point
// use 0.0 instead

// write in e format
double avogadro {6.02e23}; // 6.02 x 10^23 is a double literal in scientific notation
double protonCharge{1.6e-19}; // charge on a proton is 1.6 x 10^-19